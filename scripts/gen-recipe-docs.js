/* Generates docs/recipes.md from the registry.
 *
 * The other agent builds against that file, so a hand-maintained copy would
 * drift the moment a parameter changed and they'd emit briefs AE refuses.
 * Run after touching recipes.js:
 *
 *     node scripts/gen-recipe-docs.js
 *
 * tests/recipes-doc.test.js fails if the committed file is stale.
 */
const fs = require('node:fs');
const path = require('node:path');
const { loadEsm } = require('../tests/_load-esm');

const ROOT = path.resolve(__dirname, '..');
const R = loadEsm(path.join(ROOT, 'cep-panel-ae', 'client', 'src', 'recipes.js'));
const OUT = path.join(ROOT, 'docs', 'recipes.md');

function paramRows(params) {
  return Object.keys(params).map((k) => {
    const p = params[k];
    let type = p.type;
    if (p.type === 'enum') type = p.values.map((v) => `\`${v}\``).join(' \\| ');
    const req = p.required ? '**yes**' : '';
    const def = p.required ? '' : (p.default === '' ? '`""`'
      : p.default === null || p.default === undefined ? '—' : `\`${JSON.stringify(p.default)}\``);
    const clamp = p.clamp ? ` _(clamped: ${p.clamp})_` : '';
    return `| \`${k}\` | ${type} | ${req} | ${def} | ${p.help}${clamp} |`;
  }).join('\n');
}

function section(name) {
  const r = R.RECIPES[name];
  const badge = r.status === 'built' ? '✅ built' : '⏳ planned — will be refused if ordered';
  const lines = [
    `### \`${name}\``,
    '',
    `${badge}`,
    '',
    r.summary,
    '',
    `**Use when:** ${r.use}`,
    '',
    `**Covers archetypes:** ${r.archetypes.map((a) => `\`${a}\``).join(', ')}`,
  ];
  if (r.techniques && r.techniques.length) {
    lines.push('', `**Honours techniques:** ${r.techniques.map((t) => `\`${t}\``).join(', ')}`);
  }
  if (r.needs) lines.push('', `**Requires:** \`${r.needs}\` on the shot.`);
  lines.push('', '| prop | type | required | default | meaning |',
                 '|---|---|---|---|---|', paramRows(r.params), '');
  return lines.join('\n');
}

const built = R.builtRecipes();
const planned = Object.keys(R.RECIPES).filter((k) => R.RECIPES[k].status === 'planned');

/* The archetype map, from their twelve to my recipes. */
const ARCHETYPES = [
  'SECTION_TITLE_CARD', 'STAT_COUNTER', 'BAR_CHART', 'LINE_GRAPH', 'PIE_CHART',
  'COMPARISON_PANEL', 'FLOW_DIAGRAM', 'SCREENSHOT_HIGHLIGHT', 'DOC_HIGHLIGHT',
  'GSAP_METAPHOR', 'EMOTIONAL_MOMENT', 'BROLL_VIDEO',
];
const mapRows = ARCHETYPES.map((a) => {
  const rec = R.recipeForArchetype(a);
  if (!rec) return `| \`${a}\` | — | generate it; After Effects has no builder |`;
  const st = R.RECIPES[rec].status;
  return `| \`${a}\` | \`${rec}\` | ${st === 'built' ? 'build in AE now' : 'build in AE soon — generate for now'} |`;
}).join('\n');

const doc = `<!-- GENERATED by scripts/gen-recipe-docs.js — do not edit by hand. -->
# Recipes — what After Effects can build

The contract for anyone writing a brief. A \`recipe\` names the thing the AE
panel constructs; it is a different axis from \`archetype\` (why the script
needs the shot) and \`technique\` (how it moves). All three may share a name
without conflict.

The panel refuses any recipe not listed here, and any prop that does not
typecheck, showing you what it refused instead of building something wrong.

**Built today:** ${built.map((n) => `\`${n}\``).join(', ')}
**Planned:** ${planned.map((n) => `\`${n}\``).join(', ')}

## Techniques honoured today

${R.honouredTechniques().length
  ? R.honouredTechniques().map((t) => `\`${t}\``).join(', ')
  : '_None yet — the built recipes have fixed motion. Any `technique` you send is recorded and shown on the row as "not applied", never silently dropped._'}

## Archetype → recipe

| their archetype | my recipe | what to do |
|---|---|---|
${mapRows}

## Common props

Set on the shot, not inside \`props\`.

| prop | type | default | meaning |
|---|---|---|---|
${Object.keys(R.COMMON_PARAMS).map((k) => {
  const p = R.COMMON_PARAMS[k];
  return `| \`${k}\` | ${p.type} | \`${JSON.stringify(p.default)}\` | ${p.help} |`;
}).join('\n')}

## The recipes

${[...built, ...planned].map(section).join('\n')}`;

if (require.main === module) {
  fs.writeFileSync(OUT, doc, 'utf8');
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${built.length} built, ${planned.length} planned`);
}

module.exports = { doc, OUT };
